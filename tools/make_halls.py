# Writes src/halls.h: the Hollow Halls' interiors (the game's BigDungeon playable-area boxes), their
# Return Beacons (Prop_OpenWorld_SavePoint placements inside a box) and each hall's arrival and
# post-boss end points. Input: the overworld scene placements and area boxes extracted with the map
# mod's resource tools (C:\temp\enshrouded-re\out\shroud\placements.pkl, areas.txt).
#   python -I tools\make_halls.py
import itertools, math, pickle, re, sys, os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'halls.h')
PLACEMENTS = r'C:\temp\enshrouded-re\out\shroud\placements.pkl'
AREAS = r'C:\temp\enshrouded-re\out\shroud\areas.txt'

# The six halls in map order (west to east), keyed by the map marker that names them (its loca id).
# entrance: the overworld "Hollow Halls" map label (8kMapLabel_*_fallenCrypt_0N, where the map marker sits); end: the post-boss end zone
# (8kMapLabel_HollowHall_EndZone_placeholder_noUI) or, where a hall has none, its exit platform
# beside the boss (Teleport_Platform_SavePoint_FallenCrypt_Gameplay away from the arrival).
HALLS = [
    # marker,       region,         entrance (x, z),          arrival platform,          end point
    (0x3ad15149, 'Springlands',  (2769.691, 1425.338), (1396.5, 285.0, 8916.0), (384.0, 189.0, 8916.0)),
    (0x0356b963, 'Revelwood',    (2784.838, 3928.309), (1146.5, 221.0, 9341.5), (171.5, 136.0, 8781.0)),
    (0x12f68ccf, 'Nomad Highlands', (5937.809, 4347.662), (1789.5, 405.5, 9934.5), (174.2, 206.0, 9934.5)),
    (0x46ebe7a9, 'Veilwater Basin', (6177.825, 5809.183), (1234.25, 706.5, 8311.5), (1749.0, 821.8, 8775.0)),
    (0x16a5184d, 'Albaneve Summits', (7496.316, 6866.325), (493.5, 715.0, 9168.0), (1042.0, 571.5, 8189.8)),
    (0xb12ce8fc, 'Kindlewastes', (9039.309, 3196.662), (308.0, 555.0, 9604.5), (1728.5, 114.0, 9522.0)),
]

boxes = []
for line in open(AREAS):
    m = re.match(r'\s+area\s+\d+ min \(([-\d.]+), ([-\d.]+), ([-\d.]+)\) max \(([-\d.]+), ([-\d.]+), ([-\d.]+)\).*mapMarkerId 0x([0-9a-f]{8})', line)
    if m:
        v = [float(m.group(i)) for i in range(1, 7)]
        boxes.append((v, int(m.group(7), 16)))
markers = [h[0] for h in HALLS]
boxes = [(v, markers.index(mid)) for v, mid in boxes if mid in markers]

def hall_of(p):
    for v, h in boxes:
        if v[0] <= p[0] < v[3] and v[1] <= p[1] < v[4] and v[2] <= p[2] < v[5]:
            return h
    return None

beacons = [[] for _ in HALLS]
chests = [[] for _ in HALLS]
END_CHESTS = ('whitebox_Fallen_Crypt_Sarcophagus_end_mage', 'whitebox_Fallen_Crypt_Sarcophagus_end_ranger',
              'whitebox_Fallen_Crypt_Sarcophagus_end_warrior')
for enabled, scene, name, pos in pickle.load(open(PLACEMENTS, 'rb')):
    if name != 'Prop_OpenWorld_SavePoint' and name not in END_CHESTS:
        continue
    h = hall_of(pos)
    if h is None:
        continue
    (beacons if name == 'Prop_OpenWorld_SavePoint' else chests)[h].append((pos, name.rsplit('_', 1)[1]))
beacons = [[p for p, _ in b] for b in beacons]

def dist(a, b):
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(a, b)))

out = []
w = out.append
w('#pragma once')
w('// Generated by tools/make_halls.py; do not edit. The Hollow Halls: their interiors (the game\'s')
w('// BigDungeon playable-area boxes, which lie at the world\'s north-west edge, reached through each')
w('// hall\'s entrance), their Return Beacons, and where each hall begins and where its boss fight ends.')
w('#include <cstdint>')
w('')
w('namespace hhp::halls {')
w('')
w('struct Point { float x, y, z; };')
w('struct Hall {')
w('    uint32_t marker;     // the hall\'s map marker (also the loca id of its name)')
w('    const char* region;  // English name of the region it lies in (logs)')
w('    float entranceX, entranceZ; // the overworld map marker')
w('    Point arrival, end;  // where the entrance puts players; the boss fight\'s end zone')
w('    uint8_t first, count; // its beacons in kBeacons, in order along the hall')
w('    uint8_t firstChest, chestCount; // its end chests in kEndChests')
w('};')
w('struct Box { float minX, minY, minZ, maxX, maxY, maxZ; uint8_t hall; };')
w('')
rows = []
w('// Return Beacons (Prop_OpenWorld_SavePoint), ordered by distance from the hall\'s arrival point.')
w('constexpr Point kBeacons[] = {')
first = []
for h, (marker, region, ent, arrival, end) in enumerate(HALLS):
    bs = min(itertools.permutations(beacons[h]),
             key=lambda r: sum(dist(a, b) for a, b in zip((arrival,) + r, r + (end,))))
    first.append((len(rows), len(bs)))
    for i, p in enumerate(bs):
        rows.append(p)
        w('    {%.2ff, %.2ff, %.2ff}, // %s %d: %.0f m from the arrival, %.0f m from the end' % (p[0], p[1], p[2], region, i + 1, dist(p, arrival), dist(p, end)))
w('};')
w('')
w('// The end chests (the mage, ranger and warrior gear sarcophagi at the end of each hall: spawner points')
w('// whitebox_Fallen_Crypt_Sarcophagus_end_*, where the game places the chest). Looting one finishes the hall.')
w('constexpr Point kEndChests[] = {')
cfirst = []
for h in range(len(HALLS)):
    cfirst.append((sum(len(x) for x in chests[:h]), len(chests[h])))
    for p, kind in chests[h]:
        w('    {%.2ff, %.2ff, %.2ff}, // %s, %s' % (*p, HALLS[h][1], kind))
w('};')
w('')
w('constexpr Hall kHalls[] = {')
for h, (marker, region, ent, arrival, end) in enumerate(HALLS):
    w('    {0x%08xu, "%s", %.3ff, %.3ff, {%.2ff, %.2ff, %.2ff}, {%.2ff, %.2ff, %.2ff}, %d, %d, %d, %d},' % (
        marker, region, ent[0], ent[1], *arrival, *end, first[h][0], first[h][1], cfirst[h][0], cfirst[h][1]))
w('};')
w('constexpr int kHallCount = int(sizeof(kHalls) / sizeof(kHalls[0]));')
w('constexpr int kBeaconCount = int(sizeof(kBeacons) / sizeof(kBeacons[0]));')
w('constexpr int kEndChestCount = int(sizeof(kEndChests) / sizeof(kEndChests[0]));')
w('')
w('// Inside when min <= point < max on every axis.')
w('constexpr Box kBoxes[] = {')
for v, h in boxes:
    w('    {%.1ff, %.1ff, %.1ff, %.1ff, %.1ff, %.1ff, %d}, // %s' % (*v, h, HALLS[h][1]))
w('};')
w('')
w('}  // namespace hhp::halls')
open(OUT, 'w', newline='\n').write('\n'.join(out) + '\n')
print('wrote', OUT, len(rows), 'beacons', [c for _, c in first])
